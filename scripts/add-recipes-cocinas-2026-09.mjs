// El id se calcula aquí y no se escribe a mano: son 24 recetas repartidas en
// siete ficheros y un id repetido no lo detecta nadie hasta que dos recetas
// distintas comparten foto.
const porFichero = new Map()
for (const receta of RECETAS) {
  const file = `${receta.category}.json`
  if (!porFichero.has(file)) porFichero.set(file, [])
  porFichero.get(file).push(receta)
}

let total = 0
for (const [file, nuevas] of porFichero) {
  const path = join(RECIPES_DIR, file)
  const existentes = JSON.parse(readFileSync(path, 'utf8'))
  const prefijo = file.replace('.json', '')

  let maxNum = 0
  for (const r of existentes) {
    const m = String(r.id).match(new RegExp(`^${prefijo}_(\\d+)$`))
    if (m) maxNum = Math.max(maxNum, Number(m[1]))
  }

  const yaEstaban = new Set(existentes.map((r) => r.name))

  for (const receta of nuevas) {
    if (yaEstaban.has(receta.name)) {
      console.log(`  ↷ ya existía, se salta: ${receta.name}`)
      continue
    }
    maxNum += 1
    existentes.push({
      id: `${prefijo}_${String(maxNum).padStart(3, '0')}`,
      name: receta.name,
      category: receta.category,
      cocina: receta.cocina,
      mainProtein: receta.mainProtein,
      ...(receta.mainBase ? { mainBase: receta.mainBase } : {}),
      mealRole: receta.mealRole,
      type: receta.type,
      time: receta.time,
      difficulty: receta.difficulty,
      season: receta.season,
      kcal: receta.kcal,
      protein_g: receta.protein_g,
      carbs_g: receta.carbs_g,
      fat_g: receta.fat_g,
      baseServings: 2,
      kidFriendly: receta.kidFriendly,
      tupperFriendly: receta.tupperFriendly,
      allergens: receta.allergens,
      ingredients: receta.ingredients,
      steps: receta.steps,
      description: receta.description,
      // Sin foto todavía: ver la cabecera de este fichero.
      estrella: false,
    })
    total += 1
    console.log(`  + ${prefijo}_${String(maxNum).padStart(3, '0')}  ${receta.name}`)
  }

  writeFileSync(path, `${JSON.stringify(existentes, null, 2)}\n`, 'utf8')
}

console.log(`\n${total} recetas añadidas.`)
console.log('Siguiente: npm run build:ingredients && npm run check:catalog')
